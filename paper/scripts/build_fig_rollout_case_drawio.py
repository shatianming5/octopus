def rpc(req):
    p.stdin.write(json.dumps(req) + "\n")
    p.stdin.flush()
    if "id" not in req:
        return None
    while True:
        line = p.stdout.readline()
        if not line:
            raise RuntimeError("EOF from MCP server: " + p.stderr.read())
        if line.strip().startswith("{"):
            msg = json.loads(line)
            if msg.get("id") == req["id"]:
                return msg


